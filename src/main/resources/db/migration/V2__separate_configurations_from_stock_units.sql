UPDATE vehicles v
SET configuration_id = c.id, stock_code = 'LEGACY-' || v.id
FROM vehicle_configurations c
WHERE c.model_id = v.model_id
    AND lower(c.color) = lower(trim(v.color))
    AND lower(c.vehicle_type) = lower(COALESCE(NULLIF(trim(v.vehicle_type), ''), 'CAR'))
    AND c.specification = 'STANDARD';

