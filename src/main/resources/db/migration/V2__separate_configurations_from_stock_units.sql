CREATE TABLE vehicle_configurations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    model_id BIGINT NOT NULL REFERENCES models (id),
    color VARCHAR(50) NOT NULL CHECK (length(trim(color)) > 0),
    specification VARCHAR(100) NOT NULL CHECK (length(trim(specification)) > 0),
    vehicle_type VARCHAR(50) NOT NULL CHECK (length(trim(vehicle_type)) > 0),
    version BIGINT NOT NULL DEFAULT 0
);

CREATE UNIQUE INDEX vehicle_configurations_combination_unique
    ON vehicle_configurations (model_id, lower(color), lower(specification), lower(vehicle_type));

-- Preserve units from V1. Their previously unspecified technical variant becomes STANDARD.
INSERT INTO vehicle_configurations (model_id, color, specification, vehicle_type)
SELECT DISTINCT ON (model_id, lower(trim(color)), lower(COALESCE(NULLIF(trim(vehicle_type), ''), 'CAR')))
    model_id, trim(color), 'STANDARD', COALESCE(NULLIF(trim(vehicle_type), ''), 'CAR')
FROM vehicles
ORDER BY model_id, lower(trim(color)), lower(COALESCE(NULLIF(trim(vehicle_type), ''), 'CAR')), id;

