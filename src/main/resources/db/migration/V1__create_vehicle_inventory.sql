CREATE TABLE brands (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL CHECK (length(trim(name)) > 0)
);

CREATE UNIQUE INDEX brands_name_unique ON brands (lower(name));

CREATE TABLE models (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    brand_id BIGINT NOT NULL REFERENCES brands (id),
    name VARCHAR(100) NOT NULL CHECK (length(trim(name)) > 0)
);

CREATE UNIQUE INDEX models_brand_name_unique ON models (brand_id, lower(name));

CREATE TABLE vehicles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    model_id BIGINT NOT NULL REFERENCES models (id),
    manufacture_year INTEGER NOT NULL CHECK (manufacture_year BETWEEN 1886 AND 9999),
    color VARCHAR(50) NOT NULL CHECK (length(trim(color)) > 0),
    price NUMERIC(14, 2) NOT NULL CHECK (price >= 0),
    mileage BIGINT NOT NULL CHECK (mileage >= 0),
    vehicle_type VARCHAR(50),
    status VARCHAR(20) NOT NULL DEFAULT 'AVAILABLE'
        CHECK (status IN ('AVAILABLE', 'SOLD', 'DISCONTINUED'))
);

CREATE INDEX vehicles_model_idx ON vehicles (model_id);
CREATE INDEX vehicles_price_idx ON vehicles (price);
CREATE INDEX vehicles_manufacture_year_idx ON vehicles (manufacture_year);
CREATE INDEX vehicles_status_idx ON vehicles (status);
